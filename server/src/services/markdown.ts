import { type Report, type SectionResult, getPrivacy } from '@repoready/shared';

/**
 * Markdown export of a report (Section 13). Repo-derived text (descriptions, file names, advisory
 * summaries) is untrusted: HTML is escaped and table cells cannot break out of their row.
 */

/**
 * Plain text: neutralize HTML and collapse newlines. Only `<` can open a tag, so only it is
 * escaped (keeping e.g. "Node >=22" readable); text always follows a prefix, so a `>` can never
 * start a blockquote.
 */
export function mdText(value: string): string {
  return value.replace(/</g, '&lt;').replace(/\r?\n/g, ' ').trim();
}

/** Table cell: plain text that cannot end the cell. */
function cell(value: string): string {
  return mdText(value).replace(/\|/g, '\\|');
}

/** Inline code that survives backticks inside the value. */
export function mdCode(value: string): string {
  const clean = value.replace(/\r?\n/g, ' ');
  const longest = Math.max(0, ...(clean.match(/`+/g) ?? []).map((m) => m.length));
  const fence = '`'.repeat(longest + 1);
  const pad = clean.startsWith('`') || clean.endsWith('`') ? ' ' : '';
  return `${fence}${pad}${clean}${pad}${fence}`;
}

function section<T>(
  title: string,
  result: SectionResult<T>,
  render: (data: T) => string[],
): string[] {
  const body = result.ok ? render(result.data) : [`_Not available: ${mdText(result.error)}_`];
  return [`## ${title}`, '', ...body, ''];
}

export function buildMarkdown(report: Report, generatedAt = new Date()): string {
  const { meta } = report;
  const privacy = getPrivacy(report);
  const lines: string[] = [`# ${mdText(meta.fullName)} onboarding briefing`, ''];

  if (meta.description) lines.push(`> ${mdText(meta.description)}`, '');
  lines.push(
    `Repository: <${meta.htmlUrl}> · Commit ${mdCode(meta.commitSha.slice(0, 7))} · ` +
      `Generated by RepoReady on ${generatedAt.toISOString().slice(0, 10)}`,
    '',
  );
  if (privacy.visibility === 'private') {
    lines.push(
      '_Private repository: share this briefing only with people who may see the code._',
      '',
    );
  }

  lines.push(
    ...section('Score', report.score, (score) => [
      `**${score.total}/100 (${score.label})**`,
      '',
      '| Category | Score | Notes |',
      '| --- | --- | --- |',
      ...score.breakdown.map(
        (c) =>
          `| ${c.category} | ${c.earned}/${c.max} | ${c.reasons.map(cell).join('; ') || '-'} |`,
      ),
    ]),
  );

  lines.push(
    ...section('How to run', report.howToRun, (run) => [
      ...run.stepItems.flatMap((s, i) => {
        const out = [`${i + 1}. ${mdText(s.label)}`];
        if (s.command)
          out.push('', '   ```bash', `   ${s.command.replace(/\r?\n/g, ' ')}`, '   ```', '');
        return out;
      }),
    ]),
  );

  lines.push(
    ...section('Environment variables', report.env, (env) =>
      env.variables.length === 0
        ? ['No environment variables found in the code.']
        : [
            env.exampleFile
              ? `Example file: ${mdCode(env.exampleFile)}`
              : 'No example env file found.',
            '',
            '| Variable | Status | Used in |',
            '| --- | --- | --- |',
            ...env.variables.map(
              (v) =>
                `| ${mdCode(v.name)} | ${v.status} | ${v.usedIn.map((f) => cell(f)).join(', ') || '-'} |`,
            ),
          ],
    ),
  );

  lines.push(
    ...section('Stack', report.stack, (stack) => [
      `- Languages: ${stack.languages.map((l) => `${mdText(l.name)} ${l.percent}%`).join(', ') || 'unknown'}`,
      `- Package manager: ${stack.packageManager}`,
      ...(stack.technologies.length
        ? [`- Technologies: ${stack.technologies.map((t) => mdText(t.name)).join(', ')}`]
        : []),
      ...(stack.workspaces.length
        ? [`- Workspaces: ${stack.workspaces.map((w) => mdCode(w)).join(', ')}`]
        : []),
    ]),
  );

  lines.push(
    ...section('Checklist', report.checklist, (items) =>
      items.map(
        (i) =>
          `- [${i.passed ? 'x' : ' '}] ${mdText(i.label)}${i.passed ? '' : `: ${mdText(i.hint)}`}`,
      ),
    ),
  );

  lines.push(
    ...section('Dependencies', report.deps, (deps) => {
      const c = deps.counts;
      const out = [
        `${deps.totalPackages} packages checked (${deps.directPackages} direct). Known vulnerabilities: ` +
          `${c.critical} critical, ${c.high} high, ${c.medium} medium, ${c.low} low, ${c.unknown} unknown.`,
      ];
      if (deps.approximate)
        out.push('', '_No npm lockfile: versions were approximated from package.json ranges._');
      for (const note of deps.notes) out.push('', `_${mdText(note)}_`);
      if (deps.vulnerabilities.length) {
        out.push('', '| Package | Severity | Advisory | Fixed in |', '| --- | --- | --- | --- |');
        for (const v of deps.vulnerabilities.slice(0, 15)) {
          out.push(
            `| ${mdCode(`${v.package}@${v.version}`)} | ${v.severity} | [${cell(v.id)}](${v.url}) ${cell(v.summary)} | ${v.fixedIn ? mdCode(v.fixedIn) : '-'} |`,
          );
        }
        if (deps.vulnerabilities.length > 15) {
          out.push('', `_…and ${deps.vulnerabilities.length - 15} more._`);
        }
      }
      const majors = deps.outdated.filter((o) => o.type === 'major');
      if (majors.length) {
        out.push(
          '',
          `Major updates available: ${majors.map((o) => `${mdCode(o.name)} ${o.current} → ${o.latest}`).join(', ')}`,
        );
      }
      return out;
    }),
  );

  lines.push(
    ...section('Architecture', report.architecture, (arch) => {
      const out = [
        `${arch.analyzedFiles} files analyzed, ${arch.circular.length} circular dependencies, ` +
          `${arch.orphans.length} files nobody imports.`,
      ];
      if (arch.circular.length) {
        out.push(
          '',
          ...arch.circular
            .slice(0, 20)
            .map((cycle) => `- ${[...cycle, cycle[0]!].map((f) => mdCode(f)).join(' → ')}`),
        );
        if (arch.circular.length > 20) out.push(`- _…and ${arch.circular.length - 20} more._`);
      }
      return out;
    }),
  );

  lines.push(
    ...section('Who to ask', report.people, (people) => {
      const out: string[] = [];
      if (people.contributors.length) {
        out.push(
          `Top contributors: ${people.contributors.map((c) => `@${mdText(c.login)} (${c.commits})`).join(', ')}`,
        );
      }
      for (const f of people.byFolder) {
        out.push(
          `- ${mdCode(`${f.folder}/`)}: ${f.people.map((p) => `@${mdText(p.login)}`).join(', ')}`,
        );
      }
      return out.length ? out : ['No contributor data available.'];
    }),
  );

  return (
    lines
      .join('\n')
      .replace(/\n{3,}/g, '\n\n')
      .trimEnd() + '\n'
  );
}
